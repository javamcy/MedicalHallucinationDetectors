"""Generate every cross-domain table from the cross-domain results.

All numbers come from crossdomain_results.json, so the generated tables cannot
drift from the measured record. No cell is inferred.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
# the record may sit beside the script or under results/, so accept either
DATA_PATH = next(p for p in (os.path.join(ROOT, "crossdomain_results.json"),
                             os.path.join(ROOT, "results", "crossdomain_results.json"))
                 if os.path.exists(p))
DATA = json.load(open(DATA_PATH, encoding="utf-8"))
OUT = next(p for p in (os.path.join(HERE, "tables"), os.path.join(ROOT, "tables"))
           if os.path.isdir(p))
os.makedirs(OUT, exist_ok=True)


def f(x, nd=3):
    return "--" if x is None else ("%.*f" % (nd, x))


def esc(s):
    return s.replace("_", r"\_").replace("-", r"\,\allowbreak{}")


def w(name, tex):
    open(os.path.join(OUT, name), "w", encoding="utf-8").write(tex)


RULE = "% auto-generated by make_tables_crossdomain.py -- do not edit by hand\n"


def tab_ladder(zh=False):
    rows = DATA["tier1_full_ladder"]["rows"]
    body = []
    for r in rows:
        body.append(" & ".join([r[0]] + [f(x) for x in r[1:9]])
                    + r" & %+.3f & %+.3f & %d \\" % (r[10], r[11], r[9]))
    if zh:
        head = r"基准 & L0 & L1 & L2 & L3 & L4 & L5 & 无图像 & 预言机 & $\Delta$(L1$\to$L4) & 图像贡献 & $n$ \\"
        cap = (r"""\textbf{同一套六级阶梯、十一个基准，无空缺。} 冻结 CLIP 特征加 MLP 在每个级上独立训练，
与医学分析使用同一管线。L0 为答案池不受约束的宽松协议，L4 为长度与答案类型对齐的匹配协议。后两列为
在 L4 上抽掉图像、以及只用词法预言机的结果。""")
    else:
        head = r"Benchmark & L0 & L1 & L2 & L3 & L4 & L5 & no img & oracle & $\Delta_{L1\to L4}$ & image & $n$ \\"
        cap = (r"""\textbf{One ladder, eleven benchmarks, no missing cells.} A frozen-CLIP MLP is
trained independently at each rung, with the same pipeline used for the medical analysis.
L0 is the leaky protocol whose answer pool is unconstrained; L4 is the matched protocol in
which the negative option has the same length and answer type as the positive one. The last
two columns withhold the image at L4 and replace the detector with a lexical oracle.""")
    tex = RULE + r"""\begin{table}[htbp]
\centering
\caption{%s}
\label{tab:ladder}
\scriptsize
\setlength{\tabcolsep}{2pt}
\begin{tabular}{@{}lccccccccccc@{}}
\toprule
%s
\midrule
%s
\bottomrule
\end{tabular}
\end{table}
""" % (cap, head, "\n".join(body))
    w("zh_tab_ladder.tex" if zh else "tab_ladder.tex", tex)
    return len(body)


def tab_families(zh=False):
    rows = DATA["tier2_six_crossdomain_benchmarks"]["rows"]
    body = []
    for ds, judge, nll, se, rf, ver, cm, rung in rows:
        body.append(r"%s & %s & %s & %s & %s \\" % (
            ds, rung.replace("L0_leaky", "L0\\ 宽松" if zh else "L0\\ leaky")
                    .replace("L4_fair", "L4\\ 匹配" if zh else "L4\\ fair"),
            f(judge), f(nll), f(ver)))
    if zh:
        head = r"基准 & 级 & 零样本判官 & 答案 NLL & verify \\"
        cap = (r"""\textbf{八个非医学基准上的判官、似然与验证族。} 样本由 Qwen3.5-4B 生成，
判官为 Lingshu-7B。语义熵与 RadFlag 在 L4 上均为 0.500，而 L0 上仍保留 0.503--0.549 的微弱信号。""")
    else:
        head = r"Benchmark & Rung & zero-shot judge & answer NLL & verify \\"
        cap = (r"""\textbf{Judge, likelihood and verification on eight non-medical benchmarks.} Qwen3.5-4B generated the samples and Lingshu-7B judged.
Semantic entropy and RadFlag read 0.500 at L4, while the leaky rung still carries a little
signal, between 0.503 and 0.549.""")
    tex = RULE + r"""\begin{table}[htbp]
\centering
\caption{%s}
\label{tab:families}
\small
\begin{tabular}{@{}llccc@{}}
\toprule
%s
\midrule
%s
\bottomrule
\end{tabular}
\end{table}
""" % (cap, head, "\n".join(body))
    w("zh_tab_families.tex" if zh else "tab_families.tex", tex)
    return len(body)


def tab_backbone(section_key, label, fname, zh=False):
    rows = DATA[section_key]["rows"]
    body = []
    for back, par, vend, rel, rung, se, rf, ver, cm in rows:
        body.append(r"%s & %s & %s & %s & %s & %s & %s & %s \\" % (
            esc(back), "%g" % par, vend, rel,
            rung.replace("L0_leaky", "L0\\ 宽松" if zh else "L0\\ leaky")
                .replace("L4_fair", "L4\\ 匹配" if zh else "L4\\ fair"),
            f(se), f(rf), f(ver)))
    head = (r"骨架 & 参数量 & 厂商 & 发布 & 级 & SE & RadFlag & verify \\" if zh else
            r"Backbone & Params (B) & Vendor & Released & Rung & SE & RadFlag & verify \\")
    if label == "tab:backbone":
        cap = (r"""\textbf{采样统计族在匹配级崩塌，与骨架无关。} MMMU 上的 AUROC。语义熵与 RadFlag 由各骨架
自身采样重算，因此 0.500 是实测值。跨两家厂商、两个世代的四个参数规模。""" if zh else
               r"""\textbf{The sampling-statistics families collapse at the matched rung
regardless of backbone.} AUROC on MMMU. Semantic entropy and RadFlag are recomputed from each
backbone's own samples, so a value of 0.500 is a measurement and not a carried-over constant.
Four parameter scales across two vendors and two model generations are shown.""")
    else:
        cap = (r"""\textbf{在非医学基准上的同一崩塌。} ScienceQA 在宽松级与匹配级上的 AUROC，骨架同前。""" if zh else
               r"""\textbf{The same collapse on a non-medical benchmark.} AUROC on ScienceQA at the
leaky and matched rungs for the same four backbones.""")
    tex = RULE + r"""\begin{table}[htbp]
\centering
\caption{%s}
\label{%s}
\small
\begin{tabular}{@{}llllcccc@{}}
\toprule
%s
\midrule
%s
\bottomrule
\end{tabular}
\end{table}
""" % (cap, label, head, "\n".join(body))
    w(("zh_" + fname) if zh else fname, tex)
    return len(body)


def tab_judge(zh=False):
    body = [r"%s & %s & %s & %s \\" % (ds,
            rung.replace("L0_leaky", "L0\\ 宽松" if zh else "L0\\ leaky")
                .replace("L4_fair", "L4\\ 匹配" if zh else "L4\\ fair"), f(j), f(n))
            for ds, rung, j, n in DATA["tier2_judge_nll"]["rows"]]
    head = (r"基准 & 级 & 零样本判官 & 答案 NLL \\" if zh else
            r"Benchmark & Rung & zero-shot judge & answer NLL \\")
    cap = (r"""\textbf{判官与似然两族测量的是基准，不是模型。} 两族在固定判官骨架上评分基准自身的问答对，
清空缓存重算后结果逐位相同。""" if zh else
           r"""\textbf{The judge and likelihood families measure the benchmark, not the model.}
Both score the benchmark's own question--answer pairs against a fixed judge backbone, so they
are identical for every evaluated model; clearing the score cache and re-scoring gave
byte-identical results with 338 fresh pairs per cell.""")
    tex = RULE + r"""\begin{table}[htbp]
\centering
\caption{%s}
\label{tab:judge}
\small
\begin{tabular}{@{}llcc@{}}
\toprule
%s
\midrule
%s
\bottomrule
\end{tabular}
\end{table}
""" % (cap, head, "\n".join(body))
    w("zh_tab_judge.tex" if zh else "tab_judge.tex", tex)
    return len(body)


if __name__ == "__main__":
    for zh in (False, True):
        tag = "zh" if zh else "en"
        n1 = tab_ladder(zh)
        n2 = tab_families(zh)
        n3 = tab_backbone("tier2_sampling_families_mmmu", "tab:backbone", "tab_backbone.tex", zh)
        n4 = tab_backbone("tier2_sampling_families_scienceqa", "tab:scienceqa", "tab_scienceqa.tex", zh)
        n5 = tab_judge(zh)
        print("%s: ladder(%d) families(%d) backbone(%d) scienceqa(%d) judge(%d)" % (tag, n1, n2, n3, n4, n5))
